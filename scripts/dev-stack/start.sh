#!/usr/bin/env bash
# DEV ONLY: run a local Supabase stand-in without Docker.
#   scripts/dev-stack/start.sh          start (keeps data)
#   scripts/dev-stack/start.sh --reset  recreate the database, migrate and seed
# Needs: Postgres 16 running locally (psql as the postgres OS user), Node, curl.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DIR="$ROOT/scripts/dev-stack"
BIN="$DIR/bin"
RUN="$DIR/.run"
DB=thaali
JWT_SECRET="super-secret-jwt-token-with-at-least-32-characters-long"
mkdir -p "$BIN" "$RUN"

psql_su() { su postgres -c "psql -v ON_ERROR_STOP=1 -q $*"; }

if [ ! -x "$BIN/postgrest" ]; then
  curl -sSL https://github.com/PostgREST/postgrest/releases/download/v12.2.3/postgrest-v12.2.3-linux-static-x64.tar.xz | tar xJ -C "$BIN"
fi
if [ ! -x "$BIN/auth" ]; then
  curl -sSL https://github.com/supabase/auth/releases/download/v2.180.0/auth-v2.180.0-x86.tar.gz | tar xz -C "$BIN"
fi

stop() { for p in auth postgrest gateway; do [ -f "$RUN/$p.pid" ] && kill "$(cat "$RUN/$p.pid")" 2>/dev/null || true; rm -f "$RUN/$p.pid"; done; }
if [ "${1:-}" = "--stop" ]; then stop; exit 0; fi
stop

psql_su "-c \"alter user postgres password 'devpass'\""
if [ "${1:-}" = "--reset" ] || ! su postgres -c "psql -lqt" | cut -d\| -f1 | grep -qw "$DB"; then
  echo "• creating database $DB"
  psql_su "-c 'drop database if exists $DB with (force)'"
  psql_su "-c 'create database $DB'"
  RESET=1
fi
su postgres -c "PGOPTIONS=--client-min-messages=error psql -v ON_ERROR_STOP=1 -q -d $DB -f '$DIR/bootstrap.sql'"

DB_URL="postgres://postgres:devpass@127.0.0.1:5432/$DB"

echo "• starting auth"
cd "$BIN"
env GOTRUE_API_HOST=127.0.0.1 PORT=9999 API_EXTERNAL_URL=http://localhost:54321/auth/v1 \
  GOTRUE_DB_DRIVER=postgres GOTRUE_DB_DATABASE_URL="postgres://supabase_auth_admin:devpass@127.0.0.1:5432/$DB?search_path=auth" \
  GOTRUE_SITE_URL=http://localhost:3000 GOTRUE_URI_ALLOW_LIST="http://localhost:3000/**,http://localhost:3100/**" \
  GOTRUE_JWT_SECRET="$JWT_SECRET" GOTRUE_JWT_EXP=3600 GOTRUE_JWT_AUD=authenticated \
  GOTRUE_JWT_DEFAULT_GROUP_NAME=authenticated GOTRUE_JWT_ADMIN_ROLES=service_role \
  GOTRUE_DISABLE_SIGNUP=false GOTRUE_EXTERNAL_EMAIL_ENABLED=true GOTRUE_MAILER_AUTOCONFIRM=true \
  GOTRUE_EXTERNAL_PHONE_ENABLED=true GOTRUE_SMS_AUTOCONFIRM=true \
  GOTRUE_SMTP_HOST=127.0.0.1 GOTRUE_SMTP_PORT=2500 GOTRUE_SMTP_ADMIN_EMAIL=noreply@thaali.dev \
  GOTRUE_RATE_LIMIT_EMAIL_SENT=1000 GOTRUE_LOG_LEVEL=warn \
  ./auth > "$RUN/auth.log" 2>&1 &
echo $! > "$RUN/auth.pid"
for i in $(seq 1 60); do curl -sf http://127.0.0.1:9999/health >/dev/null && break; sleep 0.5; done
curl -sf http://127.0.0.1:9999/health >/dev/null || { cat "$RUN/auth.log"; exit 1; }

if [ "${RESET:-0}" = "1" ]; then
  echo "• applying migrations"
  for f in "$ROOT"/supabase/migrations/*.sql; do
    [ -e "$f" ] || continue
    su postgres -c "psql -v ON_ERROR_STOP=1 -q -d $DB -f '$f'" >/dev/null
  done
  su postgres -c "PGOPTIONS=--client-min-messages=warning psql -v ON_ERROR_STOP=1 -q -d $DB -f '$DIR/realtime-triggers.sql'"
fi

echo "• starting postgrest"
cat > "$RUN/postgrest.conf" <<CONF
db-uri = "postgres://authenticator:devpass@127.0.0.1:5432/$DB"
db-schemas = "public"
db-anon-role = "anon"
jwt-secret = "$JWT_SECRET"
server-host = "127.0.0.1"
server-port = 54330
db-channel-enabled = true
CONF
"$BIN/postgrest" "$RUN/postgrest.conf" > "$RUN/postgrest.log" 2>&1 &
echo $! > "$RUN/postgrest.pid"

echo "• starting gateway"
cd "$ROOT"
JWT_SECRET="$JWT_SECRET" DB_URL="$DB_URL" STORAGE_DIR="$RUN/storage" node "$DIR/gateway.mjs" > "$RUN/gateway.log" 2>&1 &
echo $! > "$RUN/gateway.pid"
for i in $(seq 1 30); do curl -sf http://127.0.0.1:54321/health >/dev/null && break; sleep 0.3; done

eval "$(node "$DIR/keys.mjs" "$JWT_SECRET")"
cat > "$ROOT/.env.local" <<ENV
# Generated by scripts/dev-stack/start.sh (local dev stack). Safe to delete.
NEXT_PUBLIC_SUPABASE_URL=http://localhost:54321
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
SUPABASE_DB_URL=$DB_URL
NEXT_PUBLIC_DEMO_MODE=true
ENV

if [ "${RESET:-0}" = "1" ] && [ -f "$ROOT/scripts/seed.ts" ]; then
  echo "• seeding"
  (cd "$ROOT" && pnpm -s seed)
fi
echo "✓ dev stack ready (gateway :54321). Env written to .env.local"
